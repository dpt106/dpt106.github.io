import math

pi = 3.141459

print("Pi rounded to 2 decimal places: " + str(round(pi, 2)))
print("Pi rounded up to nearest integer: " + str(math.ceil(pi)))
print("Pi rounded down to nearest integer: " + str(math.floor(pi)))
print("aboslute value of pi: " + str(abs(pi)))
print("pi to the power of 2: " + str(math.pow(pi, 2)))
print("Square root of pi: " + str(math.sqrt(pi)))
print("this max value is pi or 4: " + str(max(pi, 4)))
print("this min value is pi or 4: " + str(min(pi, 4)))
